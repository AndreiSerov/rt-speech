import subprocess
import wave
from pathlib import Path

import numpy as np
import pytest
from numpy.typing import NDArray

from rt_speech.audio import FRAME_SAMPLES, SAMPLE_RATE


def _say(path: Path, text: str, voice: str | None = None) -> Path:
    voice_args = ["-v", voice] if voice else []
    subprocess.run(
        [
            "say",
            *voice_args,
            "-o",
            str(path),
            "--file-format=WAVE",
            f"--data-format=LEI16@{SAMPLE_RATE}",
            text,
        ],
        check=True,
    )
    return path


@pytest.fixture(scope="session")
def speech_wav(tmp_path_factory: pytest.TempPathFactory) -> Path:
    """Real English speech, generated by macOS."""
    path = tmp_path_factory.mktemp("speech") / "en.wav"
    return _say(path, "Hello, this is a short test of voice activity detection.")


@pytest.fixture(scope="session")
def russian_speech_wav(tmp_path_factory: pytest.TempPathFactory) -> Path:
    """Real Russian speech. Needs the Milena voice, which ships with macOS."""
    path = tmp_path_factory.mktemp("speech") / "ru.wav"
    return _say(path, "Здравствуйте, это короткая проверка определения речи.", "Milena")


def read_frames(path: Path) -> list[NDArray[np.float32]]:
    with wave.open(str(path), "rb") as wav:
        data = wav.readframes(wav.getnframes())
    samples = np.frombuffer(data, dtype="<i2").astype(np.float32) / 32768.0
    usable = samples.size - samples.size % FRAME_SAMPLES
    return list(samples[:usable].reshape(-1, FRAME_SAMPLES))
